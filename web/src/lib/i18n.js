for (const lang of Object.keys(I18N)) Object.assign(I18N[lang], WEEK_I18N[lang]);

export const LANGS = Object.keys(I18N);

/** First supported language from the browser's preference list, English otherwise. */
export const detectLang = preferred =>
  preferred.map(l => l.slice(0, 2).toLowerCase()).find(l => LANGS.includes(l)) || 'en';

/** t(key, vars) fills {placeholders}; missing keys fall back to English. t.codes(n) picks the plural form. */
export function translator(lang) {
  const dict = I18N[lang];
  const rules = new Intl.PluralRules(lang);
  const t = (key, vars = {}) => (dict[key] ?? I18N.en[key]).replace(/\{(\w+)\}/g, (_, k) => vars[k]);
  t.codes = n => dict.codes[rules.select(n)] || dict.codes.other;
  return t;
}
